let lang = 'en';
try { lang = localStorage.getItem('dc-lang') || 'en'; } catch {}

export const t = (k) => dict[lang][k] ?? dict.en[k] ?? k;
export const getLang = () => lang;

export function applyI18n(root = document) {
  document.documentElement.lang = lang;
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll('[data-i18n-title]').forEach((el) => (el.title = t(el.dataset.i18nTitle)));
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
  document.title = t('appName');
  const b = document.getElementById('btnLang');
  if (b) b.textContent = lang === 'en' ? 'ने' : 'EN';
}

export function toggleLang() {
  lang = lang === 'en' ? 'ne' : 'en';
  try { localStorage.setItem('dc-lang', lang); } catch {}
  applyI18n();
}
